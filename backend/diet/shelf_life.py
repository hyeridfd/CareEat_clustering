def estimate(name: str) -> tuple[str, int]:
    """식재료명 → (분류, 보관일수)"""
    n = str(name)
    for cat, days, kws in RULES:
        if any(k in n for k in kws):
            return cat, days
    return DEFAULT


def estimate_expiry(name: str, received: dt.date) -> tuple[dt.date, str]:
    cat, days = estimate(name)
    return received + dt.timedelta(days=days), f"유통기한 추정({cat} {days}일)"
